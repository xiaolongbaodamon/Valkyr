export function getLevelTitle(level: number): { name: string; emoji: string } {
  if (level < 1) return { name: "Unranked", emoji: "🌱" };
  const [name, emoji] = levelTitles[Math.min(Math.floor(level), levelTitles.length) - 1]!;
  return { name, emoji };
}